const shortDate = (iso) => new Date(iso).toLocaleDateString("en-US", { month: "short", day: "numeric", timeZone: "UTC" });
const ago = (iso, now) => {
  const days = Math.floor((now - Date.parse(iso)) / DAY);
  if (days <= 0) return "today";
  if (days === 1) return "yesterday";
  return `${days} days ago`;
};

/** One short instruction per person, from what they did. Rules, not AI. */
export function nextStep(person, scored, now) {
  const call = person.call || {};
  const money = person.money || {};
  if (person.stages?.bought) {
    if (money.deal_cents && money.collected_cents < money.deal_cents) return { tone: "act", text: "Collect the next payment." };
    return { tone: "done", text: "Bought. Ask for their result story the day it lands." };
  }
  if (person.qualified === false || call.result === "unqualified") return { tone: "none", text: "Answers don't qualify. No call needed." };
  if (call.state === "not_closed") return { tone: "act", text: `Heard the offer on ${shortDate(call.call_at)} and didn't buy. Follow up within 48 hours.` };
  if (call.state === "follow_up") return { tone: "act", text: `Follow up: asked for time after the call on ${shortDate(call.call_at)}.` };
  if (call.state === "no_show") return { tone: "act", text: "Missed the call. Send the booking link again today." };
  if (call.state === "cancelled") return { tone: "act", text: "Cancelled the call. Rebook them today." };
  if (call.state === "upcoming") {
    const hours = (Date.parse(call.call_at) - now) / 3600000;
    return {
      tone: "wait",
      text: hours < 24 ? "Call within 24 hours. Send a reminder and a result story today." : `Call on ${shortDate(call.call_at)}. Send a short video that answers their application before then.`,
    };
  }
  if (call.state === "awaiting") return { tone: "act", text: `File the post-call form for the call on ${shortDate(call.call_at)}.` };
  if (call.state === "showed") return { tone: "act", text: "Showed up. Record whether they bought." };
  if (call.state === "closed") return { tone: "act", text: "Said yes on the call. Collect the first payment." };
  if (person.stages?.applied) {
    return { tone: "act", text: `Applied ${ago(person.stages.applied, now)} and hasn't booked. Call now${person.phone ? "" : " or email"} while they're warm.` };
  }
  if (person.stages?.app_start && person.email) return { tone: "act", text: "Started the application and stopped. Reach out today." };
  if (person.stages?.optin) {
    return scored?.band === "hot" || scored?.band === "warm"
      ? { tone: "act", text: "Engaged after opting in. Send the application link." }
      : { tone: "wait", text: "Opted in. Let the emails do the work." };
  }
  if (!person.email) return { tone: "none", text: "Anonymous. Nothing to act on until they leave an email." };
  return { tone: "wait", text: "Known visitor. Nothing to act on yet." };
}
