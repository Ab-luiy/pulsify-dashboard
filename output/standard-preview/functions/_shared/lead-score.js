// Lead score (InfoOS build; founder 2026-09-30: "build the lead score super accurately").
//
// The score is the chance this person buys, on a points scale: 50 points is a 1 in 20
// chance and every 10 points doubles the odds (the credit-scorecard convention). The
// points behind each reason add up exactly to the score, so nothing on the screen is
// a black box.
//
// The model is a logistic regression in three parts:
//   1. Where they are. The share of people at that step who went on to buy: the
//      client's own funnel once it has matured people (reached the step 30+ days ago),
//      shrunk toward all Pulsify funnels, then toward documented benchmarks, then toward
//      a labelled starting assumption where the vault has no number.
//   2. How they behaved compared with everyone else at the same step (centred, so an
//      average applicant gets no bonus and no penalty): video watched, time on the
//      page, return visits, proof read, the YouTube video they came from, and so on.
//   3. What happened: answers that don't qualify, a cancelled call, a no-show, a pitch
//      that didn't close, and days gone quiet.
// Parts 1 to 3 start from the weights below and are refit nightly on the client's own
// matured leads (MAP with the starting weights as a Gaussian prior), so they move only
// as far as the client's outcomes justify. Nothing here is generated by AI.

export const DAY = 86400000;
export const MATURE_DAYS = 30;
const POINTS_TO_DOUBLE = 10;
const FACTOR = POINTS_TO_DOUBLE / Math.LN2;
const BASE_ODDS = 1 / 19; // 50 points = 5%
const MEAN_SHRINK = 10; // pseudo-people behind a starting mean
const RATE_SHRINK = 20; // pseudo-people behind a starting step rate
export const MIN_FIT_PEOPLE = 30;
export const MIN_FIT_BUYERS = 3;

export const logit = (p) => Math.log(p / (1 - p));
export const sigmoid = (z) => 1 / (1 + Math.exp(-z));
export const pointsFromLogit = (z) => 50 + FACTOR * (z - Math.log(BASE_ODDS));
const clampP = (p) => Math.min(0.999, Math.max(0.0001, p));

export const BANDS = [
  { key: "hot", min: 65, label: "Hot" }, // about 13%+ chance to buy
  { key: "warm", min: 50, label: "Warm" }, // 5%+
  { key: "cool", min: 35, label: "Cool" }, // about 2%+
  { key: "cold", min: -Infinity, label: "Cold" },
];
export const bandFor = (score) => BANDS.find((band) => score >= band.min).key;

// The funnel ladder. A person counts as reaching every earlier step too.
export const LADDER = [
  { key: "visit", label: "Visited" },
  { key: "optin", label: "Opted in" },
  { key: "app_start", label: "Started the application" },
  { key: "applied", label: "Applied" },
  { key: "booked", label: "Booked a call" },
  { key: "showed", label: "Showed up" },
];

// Starting step rates: P(buy | reached this step). Documented where the vault has a
// number; otherwise a starting assumption, labelled as one on the screen.
export const STAGE_START = {
  showed: {
    p: 0.2,
    basis: "benchmark",
    text: "20% close rate, the low end of Jeremy Haynes' call-funnel range",
    source: "wiki/frameworks/call-funnel-framework.md",
  },
  booked: {
    p: 0.12,
    basis: "benchmark",
    text: "60% show rate x 20% close rate, the low ends of Jeremy Haynes' ranges",
    source: "wiki/frameworks/call-funnel-framework.md",
  },
  applied: { next: 0.4, of: "booked", basis: "starting", text: "starting assumption: 4 in 10 applicants book a call" },
  app_start: { next: 0.5, of: "applied", basis: "starting", text: "starting assumption: half of those who start the application finish it" },
  optin: {
    next: 0.035,
    of: "booked",
    basis: "benchmark",
    text: "3.5% of opt-ins book a call (SooWei Goh's freebie funnel)",
    source: "wiki/synthesis/soowei-goh-extractions/05-industry-predictions-blueprint.md",
  },
  visit: { next: 0.05, of: "first", basis: "starting", text: "starting assumption: 1 in 20 visitors opts in or applies" },
};

// Behaviour, compared with others at the same step. x is 0..1. mean = starting
// assumption for the average person, replaced by the client's own people. The watching
// signals (video, time, proof, scroll, button) move together, so their starting weights
// are split between them rather than each counted in full.
export const BEHAVIOUR = [
  { key: "vsl", w: 0.8, mean: 0.3, sigma: 0.5 },
  { key: "vsl_done", w: 0.2, mean: 0.1, sigma: 0.4 },
  { key: "active", w: 0.4, mean: 0.3, sigma: 0.4 },
  { key: "returned", w: 0.6, mean: 0.1, sigma: 0.5 },
  { key: "proof", w: 0.2, mean: 0.3, sigma: 0.3 },
  { key: "scroll", w: 0.1, mean: 0.4, sigma: 0.3 },
  { key: "cta", w: 0.2, mean: 0.2, sigma: 0.3 },
  { key: "youtube", w: 0.4, mean: 0.2, sigma: 0.5 },
  { key: "multi_video", w: 0.3, mean: 0.03, sigma: 0.4 },
  { key: "phone", w: 0.2, mean: 0.3, sigma: 0.3 },
  { key: "bad_email", w: -1.0, mean: 0.03, sigma: 0.5 },
];

// Until a client's own outcomes are fitted, behaviour moves the odds at most 2.0 in
// log-odds either way (about 7x). That is the documented size of being pre-sold: Jeremy
// Haynes' close rate goes from 20-30% to 40-60% with a pre-frame and show rate from
// 40-50% to 60-70% with hammer them (wiki/frameworks/call-funnel-framework.md), about
// +1.1 and +0.8 in log-odds.
export const BEHAVIOUR_CAP = 2.0;

// What happened. Not centred: they apply only when true.
export const STATES = [
  { key: "qualified", w: 0.4, sigma: 0.5 },
  { key: "unqualified", w: -2.0, sigma: 0.7 },
  { key: "cancelled", w: -0.9, sigma: 0.6 },
  { key: "no_show", w: -1.2, sigma: 0.6 },
  { key: "not_closed", w: -1.4, sigma: 0.6 },
];

// Going quiet: fixed, never refit (a matured non-buyer is quiet by definition).
export const IDLE_PER_WEEK = -0.25;
const IDLE_MAX_WEEKS = 8;

// ---------- features ----------

const ACTIVE_FULL_MINUTES = 10;

/** The 0..1 feature values for one person (built by lead-people.js). */
export function features(person) {
  const s = person.signals || {};
  const activeMinutes = Math.max(0, Number(s.active_seconds || 0)) / 60;
  return {
    vsl: Math.min(1, Math.max(0, Number(s.vsl_frac || 0))),
    vsl_done: Number(s.vsl_frac || 0) >= 0.9 ? 1 : 0,
    active: Math.min(1, Math.log2(1 + activeMinutes) / Math.log2(1 + ACTIVE_FULL_MINUTES)),
    returned: Math.min(3, Math.max(0, Number(s.days || 1) - 1)) / 3,
    proof: Number(s.proof_seconds || 0) >= 15 ? 1 : 0,
    scroll: Number(s.max_scroll || 0) >= 75 ? 1 : 0,
    cta: Number(s.ctas || 0) > 0 ? 1 : 0,
    youtube: s.youtube ? 1 : 0,
    multi_video: (s.video_ids || []).length >= 2 ? 1 : 0,
    phone: person.phone ? 1 : 0,
    bad_email: person.email && suspectEmail(person.email) ? 1 : 0,
  };
}

/** The furthest step on the ladder this person reached, among the steps this funnel has. */
export function highestStage(person, present) {
  let best = "visit";
  for (const step of LADDER) if (present.includes(step.key) && person.stages?.[step.key]) best = step.key;
  return best;
}

export function states(person) {
  return {
    qualified: person.qualified === true ? 1 : 0,
    unqualified: person.qualified === false ? 1 : 0,
    cancelled: person.call?.state === "cancelled" ? 1 : 0,
    no_show: person.call?.state === "no_show" ? 1 : 0,
    not_closed: person.call?.state === "not_closed" ? 1 : 0,
  };
}

export function idleWeeks(person, now) {
  if (person.stages?.bought) return 0;
  if (person.call?.state === "upcoming") return 0;
  const last = Date.parse(person.last_at || "");
  if (!Number.isFinite(last)) return 0;
  return Math.min(IDLE_MAX_WEEKS, Math.max(0, (now - last) / DAY - 2) / 7);
}

// Typo'd or throwaway addresses (Dustin's "email check"): the domain list is the
// common disposable services plus misspellings of the big providers.
const DISPOSABLE = new Set([
  "mailinator.com", "guerrillamail.com", "10minutemail.com", "tempmail.com", "temp-mail.org", "yopmail.com",
  "trashmail.com", "sharklasers.com", "getnada.com", "dispostable.com", "maildrop.cc", "throwawaymail.com",
  "fakeinbox.com", "mintemail.com", "mohmal.com", "emailondeck.com",
]);
const TYPOS = new Set([
  "gmial.com", "gmai.com", "gamil.com", "gmail.co", "gmail.con", "gmaill.com", "gnail.com", "hotmial.com",
  "hotmail.co", "hotmai.com", "yaho.com", "yahoo.co", "yahooo.com", "outlok.com", "outlook.co", "iclod.com", "icloud.co",
]);
export function suspectEmail(email) {
  const value = String(email || "").toLowerCase().trim();
  const at = value.lastIndexOf("@");
  if (at < 1) return true;
  const local = value.slice(0, at);
  const domain = value.slice(at + 1);
  if (!/^[^\s@]+\.[a-z]{2,}$/.test(domain)) return true;
  if (DISPOSABLE.has(domain) || TYPOS.has(domain)) return true;
  if (/^(test|asdf|qwerty|fake|none|no|na|abc|aaa+|xxx+)\d*$/.test(local)) return true;
  return false;
}

// ---------- the model ----------

/**
 * Starting model for a funnel with these steps. `pooled` (all Pulsify funnels, fitted
 * nightly) replaces the starting values where it has them.
 */
export function startingModel(present, pooled = null) {
  const stages = {};
  const chain = {};
  // Walk down the ladder from the bottom so each step can lean on the one below it.
  const order = [...LADDER].reverse().map((step) => step.key).filter((key) => present.includes(key));
  for (const key of order) {
    const start = STAGE_START[key];
    let p;
    if (start.p != null) p = start.p;
    else {
      const below = start.of === "first" ? order[order.indexOf(key) - 1] : start.of;
      const base = chain[below] ?? chain[order[order.indexOf(key) - 1]] ?? STAGE_START.booked.p;
      p = start.next * base;
    }
    const fromPool = pooled?.stages?.[key];
    if (fromPool && fromPool.basis === "client" && fromPool.people >= RATE_SHRINK) {
      stages[key] = { p: fromPool.p, basis: "pooled", text: `all Pulsify funnels: ${pct(fromPool.p)} of people at this step bought` };
    } else {
      stages[key] = { p, basis: start.basis, text: start.text, source: start.source || null };
    }
    chain[key] = stages[key].p;
  }
  const weights = {};
  for (const f of [...BEHAVIOUR, ...STATES]) weights[f.key] = pooled?.weights?.[f.key] ?? f.w;
  return { version: 1, present, stages, weights, means: pooled?.means || {}, fitted: null, basis: pooled ? "pooled" : "starting" };
}

const pct = (p) => `${Math.round(p * 1000) / 10}%`;

/**
 * Replace starting step rates with the client's own, where it has matured people.
 * `people` are the loaded people; a person counts toward a step's rate once they
 * reached it MATURE_DAYS ago (or bought).
 */
export function withOwnRates(model, people, now, { anonymousVisitors = null } = {}) {
  const cutoff = now - MATURE_DAYS * DAY;
  const next = { ...model, stages: { ...model.stages } };
  for (const key of model.present) {
    let n = 0;
    let buyers = 0;
    for (const person of people) {
      const at = Date.parse(person.stages?.[key] || "");
      const reached = key === "visit" ? Number.isFinite(Date.parse(person.first_at || "")) : Number.isFinite(at);
      if (!reached) continue;
      const when = key === "visit" ? Date.parse(person.first_at) : at;
      if (person.stages?.bought) { n += 1; buyers += 1; continue; }
      if (when <= cutoff) n += 1;
    }
    if (key === "visit" && anonymousVisitors) n += anonymousVisitors.matured;
    const prior = model.stages[key];
    const p = (buyers + RATE_SHRINK * prior.p) / (n + RATE_SHRINK);
    if (n >= 1 && buyers >= 0) {
      next.stages[key] = n >= RATE_SHRINK
        ? { p, basis: "client", people: n, buyers, text: `your funnel: ${buyers} of ${n} people who got this far bought`, prior: prior.text }
        : { ...prior, p, people: n, buyers, blended: true };
    }
  }
  // Later steps never read lower than earlier ones.
  let floor = 0;
  for (const step of LADDER) {
    const stage = next.stages[step.key];
    if (!stage) continue;
    if (stage.p < floor) next.stages[step.key] = { ...stage, p: floor };
    floor = next.stages[step.key].p;
  }
  return next;
}

/** Average behaviour per step, from the loaded people, shrunk toward the starting means. */
export function withMeans(model, people) {
  const sums = {};
  const counts = {};
  for (const person of people) {
    if (person.stages?.bought) continue;
    const stage = highestStage(person, model.present);
    const f = features(person);
    sums[stage] ||= {};
    counts[stage] = (counts[stage] || 0) + 1;
    for (const b of BEHAVIOUR) sums[stage][b.key] = (sums[stage][b.key] || 0) + f[b.key];
  }
  const means = {};
  for (const step of LADDER) {
    const prior = model.means?.[step.key] || {};
    means[step.key] = {};
    for (const b of BEHAVIOUR) {
      const start = prior[b.key] ?? b.mean;
      const n = counts[step.key] || 0;
      means[step.key][b.key] = (((sums[step.key] || {})[b.key] || 0) + MEAN_SHRINK * start) / (n + MEAN_SHRINK);
    }
    means[step.key].people = counts[step.key] || 0;
  }
  return { ...model, means };
}

/** One person's score with every reason's points. Buyers get no score. */
export function scorePerson(person, model, now) {
  if (person.stages?.bought) return { score: null, band: "customer", p: null, stage: "bought", reasons: [] };
  const stage = highestStage(person, model.present);
  const stageRate = model.stages[stage] || model.stages.visit || { p: 0.001, basis: "starting", text: "" };
  const z0 = logit(clampP(stageRate.p));
  const basePoints = Math.round(pointsFromLogit(z0));
  const reasons = [];
  let z = z0;
  let points = basePoints;
  const add = (key, contribution, extra = {}) => {
    if (!contribution) return;
    z += contribution;
    const p = Math.round(FACTOR * contribution);
    points += p;
    if (p !== 0) reasons.push({ key, points: p, ...extra });
  };
  const f = features(person);
  const means = model.means?.[stage] || {};
  const behaviour = BEHAVIOUR.map((b) => {
    const m = means[b.key] ?? b.mean;
    return { key: b.key, c: (model.weights[b.key] ?? b.w) * (f[b.key] - m), value: f[b.key], typical: Math.round(m * 100) / 100 };
  });
  const sum = behaviour.reduce((total, b) => total + b.c, 0);
  const scale = !model.fitted?.applied && Math.abs(sum) > BEHAVIOUR_CAP ? BEHAVIOUR_CAP / Math.abs(sum) : 1;
  for (const b of behaviour) add(b.key, b.c * scale, { value: b.value, typical: b.typical });
  const st = states(person);
  for (const s of STATES) if (st[s.key]) add(s.key, model.weights[s.key] ?? s.w);
  const weeks = idleWeeks(person, now);
  if (weeks > 0) add("idle", IDLE_PER_WEEK * weeks, { days: Math.round(weeks * 7 + 2) });
  reasons.sort((a, b) => Math.abs(b.points) - Math.abs(a.points));
  const score = Math.min(99, Math.max(1, points));
  return {
    score,
    band: bandFor(score),
    p: sigmoid(z),
    stage,
    base: { stage, points: basePoints, p: stageRate.p, basis: stageRate.basis, text: stageRate.text, source: stageRate.source || null },
    reasons,
    clamped: score !== points,
  };
}

// ---------- nightly refit ----------

/**
 * Fit stage rates and weights on matured people by Newton's method on the log posterior
 * (logistic likelihood, Gaussian prior centred on the current model). `rows` are
 * { person, y, weight }. Returns a new model, or the input model with fit stats when
 * there are too few outcomes.
 */
export function fitModel(model, rows, now) {
  const people = rows.reduce((n, row) => n + (row.weight || 1), 0);
  const buyers = rows.reduce((n, row) => n + (row.y ? row.weight || 1 : 0), 0);
  const present = model.present;
  if (people < MIN_FIT_PEOPLE || buyers < MIN_FIT_BUYERS) {
    return { ...model, fitted: { at: new Date(now).toISOString(), people: Math.round(people), buyers: Math.round(buyers), applied: false } };
  }
  // Parameters: intercept (visit), one increment per later step, behaviour weights, state weights.
  const params = [];
  const steps = LADDER.map((s) => s.key).filter((key) => present.includes(key));
  let prev = null;
  for (const key of steps) {
    const target = logit(clampP(model.stages[key].p));
    params.push({ kind: "stage", key, mu: prev === null ? target : Math.max(0, target - prev), sigma: prev === null ? 1 : 0.7 });
    prev = target;
  }
  for (const b of BEHAVIOUR) params.push({ kind: "behaviour", key: b.key, mu: model.weights[b.key] ?? b.w, sigma: b.sigma });
  for (const s of STATES) params.push({ kind: "state", key: s.key, mu: model.weights[s.key] ?? s.w, sigma: s.sigma });
  const d = params.length;
  const X = [];
  const Y = [];
  const C = [];
  for (const row of rows) {
    const person = row.person;
    const stage = highestStage(person, present);
    const level = steps.indexOf(stage);
    const f = features(person);
    const st = states(person);
    const means = model.means?.[stage] || {};
    X.push(params.map((p) => {
      if (p.kind === "stage") return steps.indexOf(p.key) <= level ? 1 : 0;
      if (p.kind === "behaviour") return f[p.key] - (means[p.key] ?? BEHAVIOUR.find((b) => b.key === p.key).mean);
      return st[p.key];
    }));
    Y.push(row.y ? 1 : 0);
    C.push(row.weight || 1);
  }
  let theta = params.map((p) => p.mu);
  for (let iter = 0; iter < 30; iter += 1) {
    const grad = params.map((p, j) => -(theta[j] - p.mu) / (p.sigma * p.sigma));
    const hess = Array.from({ length: d }, (_, i) => Array.from({ length: d }, (_, j) => (i === j ? -1 / (params[i].sigma * params[i].sigma) : 0)));
    for (let i = 0; i < X.length; i += 1) {
      const x = X[i];
      let z = 0;
      for (let j = 0; j < d; j += 1) z += x[j] * theta[j];
      const p = sigmoid(z);
      const r = C[i] * (Y[i] - p);
      const w = C[i] * p * (1 - p);
      for (let j = 0; j < d; j += 1) {
        if (!x[j]) continue;
        grad[j] += r * x[j];
        for (let k = 0; k < d; k += 1) if (x[k]) hess[j][k] -= w * x[j] * x[k];
      }
    }
    const step = solve(hess.map((row) => row.map((v) => -v)), grad);
    if (!step) break;
    let change = 0;
    theta = theta.map((t, j) => {
      change = Math.max(change, Math.abs(step[j]));
      return t + step[j];
    });
    if (change < 1e-6) break;
  }
  // Steps never lower the chance: clip negative increments.
  const next = { ...model, stages: { ...model.stages }, weights: { ...model.weights } };
  let z = 0;
  params.forEach((p, j) => {
    if (p.kind === "stage") {
      z += j === 0 ? theta[j] : Math.max(0, theta[j]);
      const prevStage = model.stages[p.key];
      next.stages[p.key] = { ...prevStage, p: sigmoid(z), basis: "client", fitted: true, text: `fitted on your ${Math.round(people)} matured leads, ${Math.round(buyers)} of whom bought` };
    } else {
      next.weights[p.key] = theta[j];
    }
  });
  next.fitted = { at: new Date(now).toISOString(), people: Math.round(people), buyers: Math.round(buyers), applied: true };
  next.basis = "client";
  return next;
}

// Gaussian elimination with partial pivoting: solves A x = b, or null if singular.
function solve(A, b) {
  const n = b.length;
  const M = A.map((row, i) => [...row, b[i]]);
  for (let col = 0; col < n; col += 1) {
    let pivot = col;
    for (let row = col + 1; row < n; row += 1) if (Math.abs(M[row][col]) > Math.abs(M[pivot][col])) pivot = row;
    if (Math.abs(M[pivot][col]) < 1e-12) return null;
    [M[col], M[pivot]] = [M[pivot], M[col]];
    for (let row = 0; row < n; row += 1) {
      if (row === col) continue;
      const factor = M[row][col] / M[col][col];
      if (!factor) continue;
      for (let k = col; k <= n; k += 1) M[row][k] -= factor * M[col][k];
    }
  }
  return M.map((row, i) => row[n] / M[i][i]);
}

