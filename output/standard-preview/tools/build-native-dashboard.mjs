import fs from 'node:fs';
import path from 'node:path';
// Build from a verified dashboard checkout. Runtime data is always read from D1.
const source=path.resolve(process.argv[2]||'../../.codex-tmp/phase1-dashboard/index.html');
const destination=new URL('../admin/dashboard.html',import.meta.url);
let html=fs.readFileSync(source,'utf8');
const styles=[...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)].map(m=>m[1]);
let body=html.match(/<body[^>]*>([\s\S]*?)<\/body>/i)?.[1];
if(!body||!html.includes('/api/spine/leads'))throw Error('Expected a D1-backed dashboard');
body=body.replace(/<script\b[^>]*src=["'][^"']+["'][^>]*><\/script>/gi,'')
 .replace(/(<script id="ytLeadsData"[^>]*>)[\s\S]*?(<\/script>)/,'$1[]$2');
body=body.replaceAll('fetch("/generate"','fetch("/api/dashboard-generate"').replaceAll('fetch("/transcript"','fetch("/api/transcript"');
// Global legacy theme rules cannot bleed into the host shell.
const css=styles.join('\n').replace(/:root/g,'.native-dashboard').replace(/html(?=[\s.,:#\[])/g,'.native-dashboard').replace(/\bbody\b/g,'.native-dashboard');
fs.writeFileSync(destination,'<!-- Generated by tools/build-native-dashboard.mjs. Do not edit. -->\n<style>@scope (.native-dashboard) {\n'+css+'\n}</style>\n'+body);
console.log('Built native dashboard fragment ('+fs.statSync(destination).size+' bytes)');
