// Internal build tool: the title voice bank (wiki/content-engine/title-voice-bank.md) as data for Jane.
// node tools/build-title-bank.mjs [--check]
// Founder 2026-10-27: Jane did not use our title formulas, and his own title rewrites are "the goldmine".
// Only lines in the form - `title` | thumbnail text | note, under a known heading, are read.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SOURCE_NAMES } from "../functions/_shared/source-scrub.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const source = path.join(root, "wiki/content-engine/title-voice-bank.md");
const target = path.join(root, "output/standard-preview/functions/_shared/title-bank-data.js");

// Page headings -> niche ids from functions/_shared/niches.js; "founder" is the founder's own rewrites.
const HEADINGS = {
  "founder rewrites": "founder",
  trading: "trading",
  "amazon fba": "amazon-fba",
  ecommerce: "ecommerce",
  "tiktok shop": "tiktok-shop",
  "high-ticket sales": "ht-sales",
  airbnb: "airbnb",
  "make money online": "make-money-online",
};

const bank = Object.fromEntries(Object.values(HEADINGS).map((id) => [id, []]));
let current = null;
for (const line of fs.readFileSync(source, "utf8").replace(/\r\n/g, "\n").split("\n")) {
  const heading = /^## (.+)$/.exec(line);
  if (heading) { current = HEADINGS[heading[1].trim().toLowerCase()] ?? null; continue; }
  const entry = /^- `([^`]+)` \| ([^|]+?) \| (.+)$/.exec(line);
  if (!current || !entry) continue;
  const [, title, thumbnail, note] = entry;
  if (/[—–?]/.test(title)) throw new Error(`Title breaks the house rules (dash or question mark): ${title}`);
  bank[current].push({ title: title.trim(), thumbnail: thumbnail.trim(), note: note.trim() });
}
if (!Object.entries(bank).some(([id, rows]) => id !== "founder" && rows.length)) throw new Error("No titles found in the bank.");
for (const name of SOURCE_NAMES) if (JSON.stringify(bank).toLowerCase().includes(name.toLowerCase())) throw new Error(`Source name in title bank: ${name}`);

const output = `// GENERATED by tools/build-title-bank.mjs from wiki/content-engine/title-voice-bank.md. Rebuild after editing the page.\nexport const TITLE_BANK = ${JSON.stringify(bank, null, 2)};\n`;
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== output) throw new Error("Title bank is stale. Run node tools/build-title-bank.mjs before release.");
} else fs.writeFileSync(target, output);
const counts = Object.entries(bank).map(([id, rows]) => `${id} ${rows.length}`).join(", ");
console.log(`Title bank: ${counts} (${process.argv.includes("--check") ? "current" : "built"}).`);
