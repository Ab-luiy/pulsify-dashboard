// Bundles vault method pages into functions/_shared/*-reference.js so Pages Functions can put
// them in generator prompts (Workers cannot read vault files).
// Run after editing any source page:  node tools/build-method-references.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const vault = path.resolve(here, "../../..");
const shared = path.resolve(here, "../functions/_shared");

const read = (file) => fs.readFileSync(path.join(vault, file), "utf8").replace(/\r\n/g, "\n");
const stripFrontmatter = (text) => text.replace(/^---\n[\s\S]*?\n---\n/, "").trim();
// Vault-only steps (loading files, saving to client folders) and Pulsify bookkeeping mean nothing to the model.
const dropSections = (text, headings) =>
  headings.reduce((body, heading) => body.replace(new RegExp(`\\n## ${heading}[\\s\\S]*?(?=\\n## |$)`), "\n"), text);
const PULSIFY_ONLY = ["How Pulsify uses this", "Connections", "Open questions / gaps", "Source trail"];
const methodPage = (text) => dropSections(stripFrontmatter(text), PULSIFY_ONLY);

const BUNDLES = [
  {
    out: "sequence-reference.js",
    name: "SEQUENCE_REFERENCE",
    sources: [
      {
        file: ".claude/skills/story-sequence-generator/SKILL.md",
        title: "The generator contract",
        transform: (text) => dropSections(stripFrontmatter(text), ["Load before generating", "After generating"]),
      },
      { file: "wiki/frameworks/story-sequence-system.md", title: "The story sequence system (types, 6-step arc, 9-slide frame, CTA dial)" },
      {
        file: "wiki/content-engine/sequence-breakdowns/niksetting-new-here.md",
        title: "Worked example: a real high-performing sequence broken down slide by slide. Match its texture (pill length, emphasis, where proof sits). Never copy its words or its niche",
      },
      { file: "wiki/content-engine/copy-voice-guide.md", title: "Voice guide: check every line against it before answering" },
    ],
  },
  {
    out: "youtube-reference.js",
    name: "YOUTUBE_REFERENCE",
    sources: [
      { file: "wiki/concepts/micro-niche-youtube.md", title: "Micro niche YouTube: outliers, content angle, storytelling arc", transform: methodPage },
      { file: "wiki/concepts/content-funnel-tof-mof-bof.md", title: "What each funnel stage of video is for", transform: methodPage },
      { file: "wiki/content-engine/packaging-rules.md", title: "Packaging rules: four-word title, content angle formula, hook, thumbnail", transform: methodPage },
    ],
  },
  {
    out: "youtube-packaging-reference.js",
    name: "YOUTUBE_PACKAGING_REFERENCE",
    sources: [
      { file: "wiki/content-engine/packaging-rules.md", title: "Packaging rules: four-word title, face on camera, thumbnail rules", transform: methodPage },
      {
        file: "wiki/content-engine/thumbnail-layout-patterns.md",
        title: "Thumbnail layout patterns A to D and the text treatment rule (canonical where older guidance disagrees)",
        transform: methodPage,
      },
    ],
  },
];

for (const bundle of BUNDLES) {
  const reference = bundle.sources
    .map(({ file, title, transform = stripFrontmatter }) => `=== ${title} ===\n${transform(read(file))}`)
    .join("\n\n");
  fs.writeFileSync(
    path.join(shared, bundle.out),
    `// GENERATED by tools/build-method-references.mjs from the vault. Do not edit by hand.\n` +
      `// Sources: ${bundle.sources.map((source) => source.file).join(", ")}\n` +
      `export const ${bundle.name} = ${JSON.stringify(reference)};\n`,
  );
  console.log(`wrote functions/_shared/${bundle.out} (${reference.length} chars from ${bundle.sources.length} sources)`);
}
