// Bundles the vault's story-sequence method into functions/_shared/sequence-reference.js
// so the Pages Function can put it in every generator prompt (Workers cannot read vault files).
// Run after editing any source page:  node tools/build-sequence-reference.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const vault = path.resolve(here, "../../..");
const out = path.resolve(here, "../functions/_shared/sequence-reference.js");

const read = (file) => fs.readFileSync(path.join(vault, file), "utf8").replace(/\r\n/g, "\n");
const stripFrontmatter = (text) => text.replace(/^---\n[\s\S]*?\n---\n/, "").trim();
// Vault-only steps (loading files, saving to client folders) mean nothing to the model.
const dropSections = (text, headings) =>
  headings.reduce((body, heading) => body.replace(new RegExp(`\\n## ${heading}[\\s\\S]*?(?=\\n## |$)`), "\n"), text);

const SOURCES = [
  {
    file: ".claude/skills/story-sequence-generator/SKILL.md",
    title: "The generator contract",
    transform: (text) => dropSections(stripFrontmatter(text), ["Load before generating", "After generating"]),
  },
  { file: "wiki/frameworks/story-sequence-system.md", title: "The story sequence system (types, 6-step arc, 9-slide frame, CTA dial)" },
  {
    file: "wiki/content-engine/sequence-breakdowns/niksetting-new-here.md",
    title: "Worked example: a real high-performing sequence broken down slide by slide. Match its texture (pill length, emphasis, where proof sits). Never copy its words or its niche",
  },
  { file: "wiki/content-engine/copy-voice-guide.md", title: "Voice guide: check every line against it before answering" },
];

const blocks = SOURCES.map(({ file, title, transform = stripFrontmatter }) => `=== ${title} ===\n${transform(read(file))}`);
const reference = blocks.join("\n\n");

fs.writeFileSync(
  out,
  `// GENERATED by tools/build-sequence-reference.mjs from the vault. Do not edit by hand.\n` +
    `// Sources: ${SOURCES.map((source) => source.file).join(", ")}\n` +
    `export const SEQUENCE_REFERENCE = ${JSON.stringify(reference)};\n`,
);
console.log(`wrote ${path.relative(process.cwd(), out)} (${reference.length} chars from ${SOURCES.length} sources)`);
